"""Base for the free-text criterion judges: AspectCritic and SimpleCriteriaScore.

Both put a user-written ``definition`` into the prompt's instruction, show the
judge whichever sample fields are given, and take a majority vote over
``strictness`` samples. They differ only in the prompt and in the output field
voted on (``verdict`` or ``score``).
"""

from __future__ import annotations

import typing as t
from collections import Counter

from ragas.metrics.collections._inputs import SampleFieldsInput
from ragas.metrics.collections._sampling import sample_n
from ragas.metrics.collections.base import BaseMetric
from ragas.metrics.result import MetricResult

if t.TYPE_CHECKING:
    from ragas.llms.base import InstructorBaseRagasLLM
    from ragas.prompt.metrics.base_prompt import BasePrompt


class CriteriaJudgeMetric(BaseMetric):
    """A free-text criterion, judged by majority vote over ``strictness`` samples.

    Subclasses set ``prompt_type``, ``base_instruction`` (the definition is
    appended to it) and ``vote_field``, the output field voted on.
    """

    required_components = ("llm",)

    prompt_type: t.ClassVar[t.Type["BasePrompt"]]
    base_instruction: t.ClassVar[str]
    vote_field: t.ClassVar[str]

    llm: "InstructorBaseRagasLLM"

    def __init__(
        self,
        llm: "InstructorBaseRagasLLM",
        definition: str,
        name: str,
        strictness: int,
        allowed_values: t.Tuple[float, float],
        **kwargs,
    ):
        self._definition = definition
        # Even counts can tie; the legacy implementation rounded up the same way.
        self.strictness = strictness if strictness % 2 != 0 else strictness + 1
        self.prompt = self.prompt_type()
        self._apply_definition()
        super().__init__(llm=llm, name=name, allowed_values=allowed_values, **kwargs)

    def _apply_definition(self) -> None:
        self.prompt.instruction = (
            f"{self.base_instruction}\nCriteria Definition: {self._definition}"
        )

    @property
    def definition(self) -> str:
        return self._definition

    @definition.setter
    def definition(self, value: str) -> None:
        self._definition = value
        self._apply_definition()

    async def ascore(
        self,
        user_input: t.Optional[str] = None,
        response: t.Optional[str] = None,
        retrieved_contexts: t.Optional[t.List[str]] = None,
        reference_contexts: t.Optional[t.List[str]] = None,
        reference: t.Optional[str] = None,
    ) -> MetricResult:
        """
        Judge the submission against the configured criterion.

        Args:
            user_input: The question, or a rendered multi-turn conversation
            response: The response generated by the system
            retrieved_contexts: Contexts retrieved for generating the response
            reference_contexts: Reference contexts for evaluation
            reference: The reference/ground truth answer

        Returns:
            MetricResult with the majority value and the reason given for it.
            With ``strictness`` above 1, the reason comes from the first
            judgement in the winning majority.
        """
        input_model: t.Type[SampleFieldsInput] = self.prompt.input_model
        prompt_input = input_model(
            user_input=user_input,
            response=response,
            retrieved_contexts=retrieved_contexts,
            reference_contexts=reference_contexts,
            reference=reference,
        )
        prompt_str = self.prompt.to_string(prompt_input)

        judgements = await sample_n(
            self.llm, prompt_str, self.prompt.output_model, self.strictness
        )

        votes = [getattr(j, self.vote_field) for j in judgements]
        winner = Counter(votes).most_common(1)[0][0]
        reason = next(j.reason for j, v in zip(judgements, votes) if v == winner)
        return MetricResult(value=float(winner), reason=reason)
